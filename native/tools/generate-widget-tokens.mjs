// Generates the widget colours both platforms draw from one table, widget-tokens.json:
//   iosApp/VectraWidgets/Tokens.swift   the Palette values and the plate colours (SwiftUI)
//   androidApp/src/main/res/drawable*/widget_plate*.xml   the plate drawables (Glance)
//   node tools/generate-widget-tokens.mjs           write the files
//   node tools/generate-widget-tokens.mjs --check   fail when a checked-in file is out of date (CI)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const native = join(here, '..');
const table = JSON.parse(readFileSync(join(here, 'widget-tokens.json'), 'utf8'));
const note = 'GENERATED by native/tools/generate-widget-tokens.mjs from native/tools/widget-tokens.json; do not edit.';

// "#RRGGBB", "#RRGGBB@alpha", "white", "white@alpha" or "black" as a SwiftUI Color expression.
function swiftColor(spec) {
  const [base, alpha] = spec.split('@');
  if (base === 'white' || base === 'black') return alpha ? `.${base}.opacity(${alpha})` : `.${base}`;
  const hex = `0x${base.slice(1).toUpperCase()}`;
  return alpha ? `Color(hex: ${hex}, alpha: ${alpha})` : `Color(hex: ${hex})`;
}

function swift() {
  const props = Object.entries(table.palette).map(([name, v]) =>
    `    var ${name}: Color { switch look { case .dark: ${swiftColor(v.dark)}; case .light: ${swiftColor(v.light)}; case .accented: ${swiftColor(v.accented)} } }`);
  const tones = Object.entries(table.tones).map(([kind, v]) => {
    const cases = kind === 'lab' ? '.lab, .shift' : `.${kind}`;
    return `        case ${cases}: return dark ? ${swiftColor(v.dark)} : ${swiftColor(v.light)}`;
  });
  const plate = (name) => {
    const v = table.plate[name];
    return `    static let ${name}Top: Color = ${swiftColor(v.top)}\n    static let ${name}Bottom: Color = ${swiftColor(v.bottom)}\n`
      + `    static let ${name}RimTop: Color = ${swiftColor(v.ios.rimTop)}\n    static let ${name}RimMid: Color = ${swiftColor(v.ios.rimMid)}`;
  };
  return `import SwiftUI

// ${note}

extension Palette {
${props.join('\n')}

    /// The app's session tones: lecture sky, seminar emerald, lab purple, exam violet, task amber.
    func tone(_ kind: Kind) -> Color {
        if accented { return .white }
        switch kind {
        case .lecture, .other: return accent
${tones.join('\n')}
        }
    }
}

/// The colours of the widget plate (Plate in Theme.swift): the gradient and the rim.
enum PlateTokens {
${plate('dark')}
${plate('light')}
}
`;
}

function plateXml(file) {
  const v = table.plate[file.plate];
  const a = v.android;
  const gradient = file.plate === 'clear'
    ? `android:angle="${a.angle}" android:startColor="${a.start}" android:endColor="${a.end}"`
    : `android:angle="270" android:startColor="#FF${v.top.slice(1)}" android:endColor="#FF${v.bottom.slice(1)}"`;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${file.comment} ${note} -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item>
        <shape android:shape="rectangle">
            <corners android:radius="28dp" />
            <gradient ${gradient} />
            <stroke android:width="1dp" android:color="${a.stroke}" />
        </shape>
    </item>
    <item android:bottom="2dp" android:left="16dp" android:right="16dp" android:gravity="top" android:height="1dp">
        <shape android:shape="rectangle"><solid android:color="${a.highlight}" /></shape>
    </item>
</layer-list>
`;
}

const outputs = [
  [join(native, 'iosApp', 'VectraWidgets', 'Tokens.swift'), swift()],
  ...table.androidFiles.map((f) => [join(native, 'androidApp', 'src', 'main', 'res', f.path), plateXml(f)]),
];

const check = process.argv.includes('--check');
let stale = 0;
for (const [path, text] of outputs) {
  let current = null;
  try { current = readFileSync(path, 'utf8'); } catch { /* missing */ }
  if (check) {
    if (current !== text) { console.error(`out of date: ${path}`); stale++; }
  } else if (current !== text) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${path}`);
  }
}
if (stale) {
  console.error('Run: node native/tools/generate-widget-tokens.mjs, and commit the result.');
  process.exit(1);
}
