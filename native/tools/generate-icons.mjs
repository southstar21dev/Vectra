// Generates RemixIcons.kt from the @remixicon/react package (installed in tools/).
//
//   cd tools && npm install && npm run icons
//
// The icon list is tools/icons.txt, one Remix icon name (Ri…) per line. To use a new
// icon, add its name there and re-run.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, 'package.json'));
const icons = require('@remixicon/react');

const used = new Set(
  readFileSync(join(here, 'icons.txt'), 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#')),
);
for (const name of used) {
  if (typeof icons[name] !== 'function') throw new Error(`unknown icon ${name}`);
}

function paths(element, acc = []) {
  if (!element || typeof element !== 'object') return acc;
  if (Array.isArray(element)) {
    element.forEach((e) => paths(e, acc));
    return acc;
  }
  if (element.type === 'path') acc.push(element.props.d);
  paths(element.props?.children, acc);
  return acc;
}

const entries = [...used].sort().map((name) => {
  const ds = paths(icons[name]({}));
  if (ds.length === 0) throw new Error(`no paths for ${name}`);
  const prop = name.slice(2);
  const args = ds.map((d) => `"${d}"`).join(', ');
  return `    val ${prop}: ImageVector by lazy { remixIcon("${prop}", ${args}) }`;
});

const out = `// GENERATED by native/tools/generate-icons.mjs from @remixicon/react — do not edit.
package dev.southstar21.vectra.core.designsystem.icons

import androidx.compose.ui.graphics.vector.ImageVector

object RemixIcons {
${entries.join('\n')}
}
`;
const target = join(here, '..', 'shared/src/commonMain/kotlin/dev/southstar21/vectra/core/designsystem/icons/RemixIcons.kt');
writeFileSync(target, out);
console.log(`wrote ${entries.length} icons -> ${target}`);
