// Generates RemixIcons.kt and the widget icons (Android ic_widget_*.xml drawables and iOS
// imagesets, listed in widget-icons.txt) from the @remixicon/react package (installed in tools/).
//
//   cd tools && npm install && npm run icons
//
// The icon list is tools/icons.txt, one Remix icon name (Ri…) per line. To use a new
// icon, add its name there and re-run.
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, 'package.json'));
const icons = require('@remixicon/react');

const used = new Set(
  readFileSync(join(here, 'icons.txt'), 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#')),
);
for (const name of used) {
  if (typeof icons[name] !== 'function') throw new Error(`unknown icon ${name}`);
}

function paths(element, acc = []) {
  if (!element || typeof element !== 'object') return acc;
  if (Array.isArray(element)) {
    element.forEach((e) => paths(e, acc));
    return acc;
  }
  if (element.type === 'path') acc.push(element.props.d);
  paths(element.props?.children, acc);
  return acc;
}

const entries = [...used].sort().map((name) => {
  const ds = paths(icons[name]({}));
  if (ds.length === 0) throw new Error(`no paths for ${name}`);
  const prop = name.slice(2);
  const args = ds.map((d) => `"${d}"`).join(', ');
  return `    val ${prop}: ImageVector by lazy { remixIcon("${prop}", ${args}) }`;
});

const out = `// GENERATED by native/tools/generate-icons.mjs from @remixicon/react — do not edit.
package dev.southstar21.vectra.core.designsystem.icons

import androidx.compose.ui.graphics.vector.ImageVector

object RemixIcons {
${entries.join('\n')}
}
`;
const target = join(here, '..', 'shared/src/commonMain/kotlin/dev/southstar21/vectra/core/designsystem/icons/RemixIcons.kt');
writeFileSync(target, out);
console.log(`wrote ${entries.length} icons -> ${target}`);

// Widget icons: Android vector drawables (tinted by Glance) and iOS template imagesets.
const widgetIcons = readFileSync(join(here, 'widget-icons.txt'), 'utf8')
  .split('\n')
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith('#'))
  .map((line) => line.split(/\s+/));
const drawables = join(here, '..', 'androidApp/src/main/res/drawable');
const assets = join(here, '..', 'iosApp/VectraWidgets/Assets.xcassets');
for (const [remixName, name, androidSuffix] of widgetIcons) {
  if (typeof icons[remixName] !== 'function') throw new Error(`unknown widget icon ${remixName}`);
  const ds = paths(icons[remixName]({}));
  if (ds.length === 0) throw new Error(`no paths for ${remixName}`);
  if (androidSuffix) {
    const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Remix Icon; widgets tint it. GENERATED by native/tools/generate-icons.mjs, do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
${ds.map((d) => `    <path android:fillColor="#FFFFFFFF" android:pathData="${d}" />`).join('\n')}
</vector>
`;
    writeFileSync(join(drawables, `ic_widget_${androidSuffix}.xml`), xml);
  }
  const dir = join(assets, `${name}.imageset`);
  mkdirSync(dir, { recursive: true });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24">${ds.map((d) => `<path fill="#000" d="${d}"/>`).join('')}</svg>`;
  writeFileSync(join(dir, `${name}.svg`), svg);
  const contents = {
    images: [{ filename: `${name}.svg`, idiom: 'universal' }],
    info: { author: 'xcode', version: 1 },
    properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
  };
  writeFileSync(join(dir, 'Contents.json'), JSON.stringify(contents, null, 2) + '\n');
}
console.log(`wrote ${widgetIcons.length} widget icons`);
