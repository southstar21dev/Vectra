// Generates the Android adaptive launcher icon foreground (the owl) from tools/assets/vectra.svg.
//   node tools/generate-launcher-icon.mjs
// The SVG's 1024 viewport maps onto the 108dp adaptive canvas; the owl sits inside the 66dp
// safe zone.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const svg = readFileSync(join(here, 'assets', 'vectra.svg'), 'utf8');
const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1].replace(/\s+/g, ' ').trim());
const res = join(here, '..', 'androidApp', 'src', 'main', 'res');
const vector = (color) => `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by native/tools/generate-launcher-icon.mjs from tools/assets/vectra.svg — do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="1024" android:viewportHeight="1024">
${paths.map((d) => `    <path android:fillColor="${color}" android:pathData="${d}" />`).join('\n')}
</vector>
`;
mkdirSync(join(res, 'drawable'), { recursive: true });
writeFileSync(join(res, 'drawable', 'ic_launcher_foreground.xml'), vector('#FFFFFFFF'));
console.log(`launcher icon: ${paths.length} paths`);
