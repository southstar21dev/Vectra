// Generates VectraLogo.kt (the owl brand mark) from tools/assets/vectra.svg.
//   node tools/generate-logo.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const svg = readFileSync(join(here, 'assets', 'vectra.svg'), 'utf8');
const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1].replace(/\s+/g, ' ').trim());
const out = `// GENERATED by native/tools/generate-logo.mjs from tools/assets/vectra.svg — do not edit.
package dev.southstar21.vectra.core.designsystem.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** The white owl mark; tint it for light backgrounds. */
val VectraLogo: ImageVector by lazy {
    ImageVector.Builder("VectraLogo", 1024.dp, 1024.dp, 1024f, 1024f).apply {
${paths.map((d) => `        addPath(addPathNodes(${JSON.stringify(d)}), fill = SolidColor(Color.White))`).join('\n')}
    }.build()
}
`;
writeFileSync(join(here, '..', 'shared/src/commonMain/kotlin/dev/southstar21/vectra/core/designsystem/icons/VectraLogo.kt'), out);
console.log(`logo: ${paths.length} paths`);
